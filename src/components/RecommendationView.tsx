import type { PomEvaluation, Recommendation } from "@/lib/sizing/recommend";
import { POM_LABELS } from "@/lib/types";
import { ConfidenceBadge } from "./StatusBadge";

const STATUS_TEXT: Record<PomEvaluation["status"], string> = {
  within: "Within target",
  tight: "Snug",
  loose: "Roomy",
  short: "Short",
  long: "Long",
};

const fmt = (n: number) => `${n > 0 ? "+" : ""}${n}`;

/** Ease bar: where this size's ease sits relative to the target window. */
function EaseBar({ e }: { e: PomEvaluation }) {
  const [min, max] = e.target;
  const span = Math.max(max - min, 1);
  const lo = min - span * 1.5;
  const hi = max + span * 1.5;
  const x = (v: number) => `${((Math.max(lo, Math.min(hi, v)) - lo) / (hi - lo)) * 100}%`;
  const ok = e.status === "within";
  return (
    <div style={{ position: "relative", height: 14, minWidth: 120 }} data-tip={`Target ${min} to ${max} cm · this size ${fmt(e.delta)} cm`}>
      <div style={{ position: "absolute", top: 6, left: 0, right: 0, height: 2, background: "var(--line)" }} />
      <div style={{ position: "absolute", top: 3, height: 8, left: x(min), width: `calc(${x(max)} - ${x(min)})`, background: "var(--beige-2)", borderRadius: 2 }} />
      <div
        style={{
          position: "absolute",
          top: 1,
          left: `calc(${x(e.delta)} - 6px)`,
          width: 12,
          height: 12,
          borderRadius: 6,
          background: ok ? "var(--ink)" : "var(--burgundy)",
          border: "2px solid #fffdf9",
        }}
      />
    </div>
  );
}

export function RecommendationView({
  rec,
  explanation,
  explanationSource,
  productName,
  compact = false,
}: {
  rec: Recommendation;
  explanation: string;
  explanationSource: "bedrock" | "template";
  productName: string;
  compact?: boolean;
}) {
  const best = rec.sizes.find((s) => s.size === rec.recommendedSize);
  const ranked = [...rec.sizes].sort((a, b) => a.penalty - b.penalty);
  const compareLabel = rec.mode === "body" ? "Your measurement" : "Reference garment";

  return (
    <div className="stack">
      <div className="row between" style={{ alignItems: "flex-end" }}>
        <div>
          <div className="eyebrow">Suggested size · {productName}</div>
          <div className="display" style={{ fontSize: compact ? "3.4rem" : "4.4rem", lineHeight: 1 }}>
            {rec.recommendedSize ?? "—"}
            {rec.betweenSizes && rec.runnerUp && (
              <span className="muted" style={{ fontSize: "1.4rem", marginLeft: 12 }}>or {rec.runnerUp}</span>
            )}
          </div>
        </div>
        <ConfidenceBadge confidence={rec.confidence} />
      </div>

      <p style={{ fontSize: 15 }}>{explanation}</p>
      <p className="tiny muted" style={{ marginTop: -8 }}>
        {explanationSource === "bedrock"
          ? "Wording generated by Amazon Bedrock from the calculation below. The size itself was chosen by the measurement engine."
          : "Explanation assembled directly from the calculation below."}{" "}
        {rec.confidenceReasons.join(" ")}
      </p>

      {rec.missingInputs.length > 0 && (
        <div className="callout neutral small">Add your {rec.missingInputs.join(", ")} measurement to compare more points of measure.</div>
      )}

      {best && (
        <div>
          <h3 style={{ fontSize: "1.2rem", marginBottom: 8 }}>How size {best.size} was calculated</h3>
          <div className="table-wrap">
            <table className="data" style={{ fontSize: 13 }}>
              <thead>
                <tr>
                  <th>Point of measure</th>
                  <th className="num">Garment</th>
                  <th className="num">{compareLabel}</th>
                  <th className="num">{rec.mode === "body" ? "Ease" : "Difference"}</th>
                  <th className="num">Target</th>
                  <th style={{ minWidth: 140 }}>Position</th>
                  <th>Result</th>
                  <th className="num">Weight</th>
                  <th className="num">Penalty</th>
                </tr>
              </thead>
              <tbody>
                {best.evaluations.map((e) => (
                  <tr key={e.pom}>
                    <td>{POM_LABELS[e.pom]}</td>
                    <td className="num mono">{e.garment}</td>
                    <td className="num mono">{e.compareTo}</td>
                    <td className="num mono">{fmt(e.delta)}</td>
                    <td className="num mono" style={{ whiteSpace: "nowrap" }}>{e.target[0]} to {e.target[1]}</td>
                    <td><EaseBar e={e} /></td>
                    <td>
                      <span className={`badge ${e.status === "within" ? "good" : "warn"}`}>{STATUS_TEXT[e.status]}</span>
                    </td>
                    <td className="num mono">×{e.weight}</td>
                    <td className="num mono">{e.penalty}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
          {best.hardStops.length > 0 && <p className="small" style={{ color: "var(--bad)" }}>▲ {best.hardStops.join("; ")}.</p>}
        </div>
      )}

      {!compact && rec.sizes.length > 0 && (
        <div>
          <h3 style={{ fontSize: "1.2rem", marginBottom: 8 }}>Every size, scored</h3>
          <p className="small muted">
            Penalty = cm outside the target range × weight (snug is weighted ×1.5 because a garment that is too small can't be worn). Lowest
            penalty wins; near-ties follow your fit preference.
          </p>
          <div className="table-wrap">
            <table className="data" style={{ fontSize: 13 }}>
              <thead>
                <tr>
                  <th>Size</th>
                  {rec.comparedPoms.map((p) => (
                    <th key={p} className="num">{POM_LABELS[p]}</th>
                  ))}
                  <th className="num">Total penalty</th>
                </tr>
              </thead>
              <tbody>
                {rec.sizes.map((s) => (
                  <tr key={s.size} className={s.size === rec.recommendedSize ? "hl" : ""}>
                    <td style={{ fontWeight: 600 }}>
                      {s.size} {s.size === rec.recommendedSize ? "★" : ranked[1]?.size === s.size ? <span className="tiny muted">runner-up</span> : null}
                    </td>
                    {rec.comparedPoms.map((p) => {
                      const e = s.evaluations.find((x) => x.pom === p);
                      return (
                        <td key={p} className="num mono" data-tip={e ? `${STATUS_TEXT[e.status]} · target ${e.target[0]} to ${e.target[1]}` : ""}>
                          {e ? `${fmt(e.delta)} cm` : "—"}
                          {e && e.status !== "within" ? <span className="muted"> ({e.penalty})</span> : null}
                        </td>
                      );
                    })}
                    <td className="num mono" style={{ fontWeight: 600 }}>{s.penalty}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      <details>
        <summary className="small" style={{ cursor: "pointer", fontWeight: 500 }}>Limitations of this recommendation</summary>
        <ul className="small muted" style={{ marginTop: 8 }}>
          {rec.limitations.map((l) => (
            <li key={l}>{l}</li>
          ))}
        </ul>
      </details>
    </div>
  );
}
